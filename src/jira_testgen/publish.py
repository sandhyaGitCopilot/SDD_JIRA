@dataclass
class PreflightResult:
    draft: DraftSet
    warnings: list[str]
    overrides: dict
    project_key: str


def _check_approval(draft: DraftSet, path: Path) -> str:
    """Return the fingerprint this run is publishing, or refuse.

    Side effect by design: a voided approval resets the file to ``draft`` so a
    stale marker cannot sit there looking approved (FR-046).
    """
    current = content_fingerprint(draft)

    if not draft.approval.is_approved:
        raise DraftRefusedError(
            f"{path} is not approved, so nothing was published.\n"
            "Review the test cases, then set `status: approved` in that file and "
            "run this command again."
        )

    recorded = draft.approval.approved_fingerprint
    if recorded is None:
        # First approved run: record the baseline the engineer approved.
        draft.approval.approved_fingerprint = current
        dump_draft(draft, path)
        return current

    if recorded != current:
        draft.approval.status = "draft"
        draft.approval.approved_fingerprint = None
        dump_draft(draft, path)
        raise DraftRefusedError(
            f"{path} changed after it was approved, so nothing was published.\n"
            "The approval has been voided and the file reset to `status: draft`. "
            "Review the current content and approve it again."
        )

    return current


def _check_targets(client: JiraClient, config: Config, project_key: str) -> None:
    """Verify the project, issue type and link type before creating anything."""
    # Raised as UserError, not PermanentError: both of these name a setting the
    # engineer can fix, so they belong with the configuration errors (exit 2)
    # rather than looking like a tool fault (FR-024, FR-032).
    meta = issues.get_create_meta(
        client, project_key=project_key, issue_type=config.test_issue_type
    )
    if not meta:
        raise UserError(
            f"Issue type '{config.test_issue_type}' cannot be created in project "
            f"{project_key}. Set JIRA_TEST_ISSUE_TYPE to a type this project accepts."
        )

    available = issues.list_link_type_names(client)
    if config.link_type not in available:
        raise UserError(
            f"Link type '{config.link_type}' does not exist on this Jira site. "
            f"Set JIRA_LINK_TYPE to one of: {', '.join(sorted(available)) or '(none found)'}."
        )


def _check_criteria_freshness(
    client: JiraClient,
    draft: DraftSet,
    *,
    ac_field: str | None,
    allow_stale: bool,
) -> list[str]:
    """Compare the story's criteria against the draft's recorded baseline.

    Formatting-only differences are invisible here, because Jira's editor
    rewrites markup on unrelated edits and a gate that fired on that would be
    unusable (FR-057).
    """
    story = issues.get_story(client, draft.source_issue, ac_field=ac_field)
    live = extract_criteria(
        description_text=story.description_text,
        ac_field_text=story.ac_field_text,
        ac_field=ac_field,
    )

    drafted = [(c.label, normalize_for_comparison(c.source_text)) for c in draft.criteria]
    current = [(c.label, c.normalized) for c in live.criteria]

    changes: list[str] = []
    for (label, was), (_live_label, now) in zip(drafted, current, strict=False):
        if was != now:
            changes.append(
                f'{label} changed in Jira: drafted as "{_find_source(draft, label)}", '
                f'now "{_find_live(live, label)}"'
            )

    if len(current) > len(drafted):
        for extra in current[len(drafted) :]:
            changes.append(f'a new criterion was added in Jira: "{extra[1]}"')
    elif len(current) < len(drafted):
        for missing in drafted[len(current) :]:
            changes.append(f"{missing[0]} was removed from the story in Jira")

    if changes and not allow_stale:
        raise CriteriaChangedError(
            f"{draft.source_issue}'s acceptance criteria changed after these drafts "
            "were approved, so nothing was published:\n  - "
            + "\n  - ".join(changes)
            + "\nRegenerate the drafts with `prepare --regenerate` so the test cases "
            "match the story, or re-run with --allow-stale-criteria to publish anyway."
        )
    return changes


def _find_source(draft: DraftSet, label: str) -> str:
    for criterion in draft.criteria:
        if criterion.label == label:
            return criterion.source_text
    return "(not in draft)"


def _find_live(live, label: str) -> str:
    for criterion in live.criteria:
        if criterion.label == label:
            return criterion.source_text
    return "(removed)"


