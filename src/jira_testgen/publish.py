# ---------------------------------------------------------------------------
# Issue content (T055)
# ---------------------------------------------------------------------------


def build_issue_summary(case: TestCase) -> str:
    """The Jira summary for a test case.

    Truncated to Jira's 255-character limit as a backstop. `validate` already
    rejects an over-long summary, so reaching the truncation here means the
    draft bypassed validation -- better a shortened summary than a rejected
    create halfway through a run.
    """
    summary = case.summary.strip()
    if len(summary) <= MAX_SUMMARY_LENGTH:
        return summary
    return summary[: MAX_SUMMARY_LENGTH - 1].rstrip() + "…"


def build_issue_description(case: TestCase, *, story_key: str) -> dict:
    """The Jira description as ADF.

    Category and covered criteria are rendered into the body so a reader sees
    the traceability without needing this tool (FR-018).
    """
    from jira_testgen.jira import adf

    covers = ", ".join(case.covers) if case.covers else "(none recorded)"
    return adf.doc(
        adf.paragraph(
            f"Manual test case for {story_key} — {case.category} scenario. "
            f"Covers: {covers}."
        ),
        adf.heading("Preconditions"),
        adf.paragraph(case.preconditions.strip() or "None."),
        adf.heading("Steps"),
        adf.ordered_list([str(step).strip() for step in case.steps]),
        adf.heading("Expected results"),
        adf.paragraph(case.expected_results.strip()),
        adf.paragraph(f"Generated by jira-testgen {__version__}. Identity: {case.identity}."),
    )


