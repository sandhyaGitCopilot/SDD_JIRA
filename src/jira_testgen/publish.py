def _discover_all(client: JiraClient, story, draft: DraftSet) -> dict:
    """Everything already published for this story, from Jira alone.

    Two passes, because one is not enough. Walking the story's links finds the
    normal case. But an issue that was created and never linked is not among
    them -- so any test case still unaccounted for is looked up by its identity
    label, which is the only JQL-reachable handle on it. Without this second
    pass a re-run would create a duplicate of every unlinked issue
    (FR-023, FR-027).
    """
    from jira_testgen.jira.properties import read_marker
    from jira_testgen.jira.search import find_issues_by_identities

    published = issues.discover_published(client, story)

    missing = [c.identity for c in draft.test_cases if c.identity not in published]
    if not missing:
        return published

    for identity, issue_key in find_issues_by_identities(client, missing).items():
        marker = read_marker(client, issue_key)
        if marker is None or marker.identity != identity:
            # Carries the label but not our marker: not ours to touch (FR-026c).
            continue
        published[identity] = issues.PublishedTestCase(
            identity=identity,
            issue_key=issue_key,
            marker=marker,
            link_present=issue_key in story.linked_issue_keys,
        )
    return published


@dataclass
class Decision:
    """What to do about one test case, and why."""

    action: str
    issue_key: str | None = None
    reason: str | None = None
    fields_differing: list[str] = field(default_factory=list)


def _rendered_draft(case: TestCase, story_key: str) -> tuple[str, str]:
    """What this test case *would* look like in Jira right now."""
    from jira_testgen.jira.adf import extract_text

    summary = build_issue_summary(case)
    body = extract_text(build_issue_description(case, story_key=story_key)).text
    return summary, body


def decide(
    client: JiraClient,
    case: TestCase,
    published: dict,
    *,
    story_key: str,
) -> Decision:
    """Work out what one test case needs, from Jira's state alone.

    The verdict comes from two independent comparisons, which is what keeps the
    outcomes mutually exclusive and testable (data-model.md):

    - **stored vs the issue now** -- did a person edit it in Jira?
    - **stored vs the draft now** -- did the engineer edit the draft?

    | issue   | draft     | outcome   |
    |---------|-----------|-----------|
    | matches | unchanged | unchanged |
    | matches | changed   | update    |
    | differs | either    | conflict  |

    The issue's ``updated`` timestamp is deliberately never consulted:
    automations, workflow transitions and comments all bump it, and every one
    would produce a phantom conflict.
    """
    existing = published.get(case.identity)
    if existing is None:
        return Decision("create")

    content = issues.get_issue_content(client, existing.issue_key)
    if not content.exists:
        # Someone deleted it. Reporting it as present would leave the story
        # quietly under-tested (FR-028).
        return Decision(
            "recreate",
            reason=f"{existing.issue_key} no longer exists in Jira; re-creating it.",
        )

    stored = existing.marker.content_fingerprint
    issue_now = rendered_fingerprint(content.summary, content.description_text)
    draft_summary, draft_body = _rendered_draft(case, story_key)
    draft_now = rendered_fingerprint(draft_summary, draft_body)

    if stored != issue_now:
        differing = []
        if collapse(content.summary) != collapse(draft_summary):
            differing.append("summary")
        if collapse(content.description_text) != collapse(draft_body):
            differing.append("description")
        return Decision(
            "conflict",
            issue_key=existing.issue_key,
            fields_differing=differing or ["description"],
            reason=(
                f"{existing.issue_key} was edited in Jira after this tool last wrote "
                "it, so it was left untouched. Resolve it by restoring the issue, or "
                "by changing the draft to match, then re-run."
            ),
        )

    if not existing.link_present:
        return Decision("relink", issue_key=existing.issue_key)

    if stored == draft_now:
        return Decision("unchanged", issue_key=existing.issue_key)

    return Decision("update", issue_key=existing.issue_key)


# ---------------------------------------------------------------------------
# The run
# ---------------------------------------------------------------------------


def publish_draft(
    client: JiraClient,
    issue_key: str,
    *,
    drafts_dir: str | Path = DEFAULT_DRAFTS_DIR,
    config: Config | None = None,
    ac_field: str | None = None,
    allow_large: bool = False,
    allow_stale_criteria: bool = False,
) -> RunReport:
    """Publish an approved draft. The only function here that writes to Jira."""
    log = get_logger()
    key = validate_issue_key(issue_key)
    path = draft_path(drafts_dir, key)
    effective = config or client.config
    ac = ac_field if ac_field is not None else effective.ac_field

    draft = load_draft(path)

    # 1. Structure.
    validation = validate_draft(draft, source=str(path))
    if not validation.ok:
        raise DraftRefusedError(
            f"{path} is not publishable yet:\n  - " + "\n  - ".join(validation.errors)
        )

    # 2. Approval.
    _check_approval(draft, path)

    report = RunReport(
        source_issue=key,
        criteria_source=draft.criteria_source,
        defaults_used=dict(effective.defaults_used),
        warnings=list(validation.warnings),
    )

    project_key = effective.project_key or ""

    # 3. Targets. Needs the story's project when none is configured.
    story = issues.get_story(client, key, ac_field=ac)
    if not project_key:
        project_key = story.project_key
        report.defaults_used["JIRA_PROJECT_KEY"] = project_key
    _check_targets(client, effective, project_key)

    # 4. Criteria freshness.
    changes = _check_criteria_freshness(
        client, draft, ac_field=ac, allow_stale=allow_stale_criteria
    )
    if changes:
        report.overrides_used["stale_criteria"] = changes

    # 5. Ceiling.
    count = len(draft.test_cases)
    if limits.exceeds_ceiling(count):
        if not allow_large:
            raise SetTooLargeError(limits.ceiling_message(count))
        report.overrides_used["set_size"] = count

    # Everything below this line may write to Jira.
    published = _discover_all(client, story, draft)
    log.info("publishing %d test case(s) for %s", count, key)

    expected = [case.identity for case in draft.test_cases]

    for case in draft.test_cases:
        # Per test case, so the report can name the slow ones (FR-055).
        client.reset_retry_count()
        before = len(report.outcomes)
        try:
            _publish_one(
                client,
                case,
                decision=decide(client, case, published, story_key=key),
                report=report,
                config=effective,
                project_key=project_key,
                story_key=key,
            )
        except AmbiguousResultError as exc:
            # The write may have landed. Resolving this by identity is the only
            # thing standing between a retry and a duplicate (FR-053).
            _recover_ambiguous(
                client,
                case,
                report=report,
                config=effective,
                story_key=key,
                reason=exc.message,
            )
        except TransientError as exc:
            # A Jira-wide condition rather than one bad test case: stop, and
            # leave the run resumable (FR-054).
            log.warning("stopping after exhausted retries: %s", exc.message)
            report.add(
                Outcome(
                    identity=case.identity,
                    decision="failed",
                    reason=f"Retries exhausted: {exc.message}",
                )
            )
            break
        except PermanentError as exc:
            # One test case cannot be published; the rest still can (FR-020).
            report.add(
                Outcome(identity=case.identity, decision="failed", reason=exc.reason)
            )

        # Attribute this test case's retries to whatever outcome it produced,
        # in one place rather than at every report.add call site.
        if client.retries:
            for outcome in report.outcomes[before:]:
                outcome.retried = client.retries

    # Anything published for this story that the draft no longer mentions. The
    # issue is left alone, but reported, so nothing created goes unaccounted for.
    drafted = {case.identity for case in draft.test_cases}
    for identity, item in sorted(published.items()):
        if identity in drafted:
            continue
        report.add(
            Outcome(
                identity=identity,
                decision="orphaned_draft",
                issue_key=item.issue_key,
                reason=(
                    f"{item.issue_key} is published for {key} but is no longer in the "
                    "draft. It was left in place; delete it in Jira if you meant to "
                    "drop this test case."
                ),
            )
        )
        expected.append(identity)

    return report.finalize(expected)


def _recover_ambiguous(
    client: JiraClient,
    case: TestCase,
    *,
    report: RunReport,
    config: Config,
    story_key: str,
    reason: str,
) -> None:
    """Resolve a write whose outcome is unknown, by identity (FR-053).

    Jira's create endpoint offers no idempotency key, which is exactly why the
    identity is stored as a JQL-searchable label. If the create did land, the
    issue is adopted -- its marker refreshed and its link ensured -- rather than
    created a second time.
    """
    from jira_testgen.jira.search import find_issue_by_identity

    log = get_logger()
    existing_key = find_issue_by_identity(client, case.identity, sleep=client.sleep)

    if not existing_key:
        # Nothing landed. Reporting this as created would be a lie; a re-run
        # creates it properly.
        report.add(
            Outcome(
                identity=case.identity,
                decision="failed",
                reason=(
                    f"Outcome unknown and no issue carries this identity: {reason} "
                    "Nothing appears to have been created; re-run to publish it."
                ),
            )
        )
        return

    log.info("adopting %s for %s after an unclear write", existing_key, case.identity)
    _finish_created(
        client,
        case,
        issue_key=existing_key,
        report=report,
        config=config,
        story_key=story_key,
        decision="adopted",
        reason=(
            f"The create timed out, but {existing_key} carries this identity, so it "
            "was adopted instead of being created again."
        ),
    )


def _publish_one(
    client: JiraClient,
    case: TestCase,
    *,
    decision: Decision,
    report: RunReport,
    config: Config,
    project_key: str,
    story_key: str,
) -> None:
    """Apply one decision, recording exactly one outcome for it."""
    if decision.action == "unchanged":
        report.add(
            Outcome(identity=case.identity, decision="unchanged", issue_key=decision.issue_key)
        )
        return

    if decision.action == "conflict":
        # Nothing is written. Both sides are left exactly as they are, and the
        # report says which fields differ (FR-039).
        report.add(
            Outcome(
                identity=case.identity,
                decision="conflict",
                issue_key=decision.issue_key,
                reason=decision.reason,
                fields_differing=list(decision.fields_differing),
            )
        )
        return

    if decision.action == "relink":
        issues.link_issues(
            client,
            link_type=config.link_type,
            inward_key=decision.issue_key or "",
            outward_key=story_key,
        )
        report.add(
            Outcome(identity=case.identity, decision="relinked", issue_key=decision.issue_key)
        )
        return

    if decision.action == "update":
        summary, body = _rendered_draft(case, story_key)
        issues.update_issue(
            client,
            decision.issue_key or "",
            summary=summary,
            description=build_issue_description(case, story_key=story_key),
        )
        # Refresh the fingerprint, or the next run would read the issue it just
        # wrote as having been edited by someone else (FR-040).
        write_marker(
            client,
            decision.issue_key or "",
            _marker_for(case, story_key, summary, body),
        )
        report.add(
            Outcome(identity=case.identity, decision="updated", issue_key=decision.issue_key)
        )
        return

    # create, or recreate after the previous issue was deleted in Jira
    new_key = issues.create_issue(
        client,
        project_key=project_key,
        issue_type=config.test_issue_type,
        summary=build_issue_summary(case),
        description=build_issue_description(case, story_key=story_key),
        labels=[identity_to_label(case.identity)],
    )
    _finish_created(
        client,
        case,
        issue_key=new_key,
        report=report,
        config=config,
        story_key=story_key,
        decision="recreated" if decision.action == "recreate" else "created",
        reason=decision.reason,
    )


def _marker_for(
    case: TestCase, story_key: str, summary: str, body: str
) -> PublicationMarker:
    return PublicationMarker(
        identity=case.identity,
        content_fingerprint=rendered_fingerprint(summary, body),
        source_issue=story_key,
        generated_at=datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        tool_version=__version__,
    )


def _finish_created(
    client: JiraClient,
    case: TestCase,
    *,
    issue_key: str,
    report: RunReport,
    config: Config,
    story_key: str,
    decision: str,
    reason: str | None = None,
) -> None:
    """Attach the marker and the link to a newly created or adopted issue.

    The marker goes on **before** the link, deliberately. Without it the issue
    is invisible to every later run, which means a duplicate next time -- a
    worse outcome than a missing link, which a re-run simply completes.
    """
    summary, body = _rendered_draft(case, story_key)

    try:
        write_marker(client, issue_key, _marker_for(case, story_key, summary, body))
    except PermanentError as exc:
        report.add(
            Outcome(
                identity=case.identity,
                decision="created_unmarked",
                issue_key=issue_key,
                reason=(
                    f"Created, but its identity marker could not be written ({exc.reason}). "
                    "A later run will not recognise it; add the marker or delete the issue."
                ),
            )
        )
        return

    try:
        issues.link_issues(
            client,
            link_type=config.link_type,
            inward_key=issue_key,
            outward_key=story_key,
        )
    except PermanentError as exc:
        report.add(
            Outcome(
                identity=case.identity,
                decision="created_unlinked",
                issue_key=issue_key,
                reason=(
                    f"Created, but could not be linked to {story_key} ({exc.reason}). "
                    "Re-run to complete the link."
                ),
            )
        )
        return

    report.add(
        Outcome(
            identity=case.identity,
            decision=decision,
            issue_key=issue_key,
            reason=reason,
        )
    )
