"""Publishing: pre-flight, then the loop that writes to Jira.

Order is the whole design here. Nothing is created until every gate has passed,
because a half-published story is far more annoying than a refused one:

1. the draft is structurally valid (FR-017);
2. the approval marker is set, and still applies to this content
   (FR-016, FR-043, FR-046);
3. the target project, issue type and link type are usable (FR-024);
4. the story's criteria have not moved on since drafting (FR-056 - FR-059);
5. the set is within the publishing ceiling (FR-065).

Only then does the loop run. A permanent failure on one test case is reported
and the loop continues (FR-020); a Jira-wide condition stops the run with a
resumable report (FR-054).
"""

